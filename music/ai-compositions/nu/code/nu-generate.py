#!/usr/bin/env python3
"""Generates nu.csd: bells walking at random on D Dorian over a drone.

Run it from the directory that is to contain nu.csd:

    python code/nu-generate.py

The random seed is taken from the environment variable STUDIO_SEED
(default 7), so the same seed always produces the same .csd.
"""
import os
import random

import CsoundAC

SEED = int(os.environ.get("STUDIO_SEED", "7"))
TONIC = 62  # D4
DORIAN = [0, 2, 3, 5, 7, 9, 10]
BELL, DRONE, REVERB = 1.0, 2.0, 99
NOTE_ON = 144.0
ALL_PITCH_CLASSES = 4095.0

ORCHESTRA = r"""
sr = 48000
ksmps = 16
nchnls = 2
0dbfs = 1

; nu -- a short study: bells in D Dorian over a drone.
;
; Score p-fields:
;   p1 instrument    p2 time (seconds)    p3 duration (seconds)
;   p4 MIDI key      p5 MIDI velocity
;   p6 depth, front to back (0 near .. 1 far)
;   p7 pan, left to right (0 left .. 1 right)
;   p8 height        p9 phase    p10 pitch-class set    p11 homogeneity

gaReverbLeft init 0
gaReverbRight init 0

; Bell: two-operator FM, struck.
instr 1
  iHz = cpsmidinn(p4)
  iAmp = ampdbfs(-19 + 18 * (p5 / 127))
  iDepth = limit(p6, 0, 1)
  iPan = limit(p7, 0, 1)
  aAttack linseg 0, 0.004, 1, p3, 1
  aDecay expseg 1, p3, 0.001
  kIndex expseg 3.2, p3 * 0.6, 0.15, p3 * 0.4, 0.1
  aModulator poscil kIndex * iHz * 3.5, iHz * 3.5
  aCarrier poscil aAttack * aDecay * iAmp, iHz + aModulator
  aLeft, aRight pan2 aCarrier, iPan
  iDirect = 1 - 0.6 * iDepth
  iSend = 0.2 + 0.6 * iDepth
  out aLeft * iDirect, aRight * iDirect
  gaReverbLeft += aLeft * iSend
  gaReverbRight += aRight * iSend
endin

; Drone: two detuned sawtooths and a sub-octave sine through a slow filter.
instr 2
  iHz = cpsmidinn(p4)
  iAmp = ampdbfs(-26 + 18 * (p5 / 127))
  iPan = limit(p7, 0, 1)
  aEnvelope linseg 0, p3 * 0.3, 1, p3 * 0.4, 1, p3 * 0.3, 0
  aSawLow vco2 1, iHz * 0.998
  aSawHigh vco2 1, iHz * 1.002
  aSub poscil 1, iHz * 0.5
  kCutoff linseg 300, p3 * 0.5, 900, p3 * 0.5, 300
  aFiltered moogladder (aSawLow + aSawHigh) * 0.3 + aSub * 0.5, kCutoff, 0.2
  aSignal = aFiltered * aEnvelope * iAmp
  aLeft, aRight pan2 aSignal, iPan
  out aLeft, aRight
  gaReverbLeft += aLeft * 0.3
  gaReverbRight += aRight * 0.3
endin

; Reverberation for everything sent to the reverb bus.
instr 99
  aLeft, aRight reverbsc gaReverbLeft, gaReverbRight, 0.86, 9000
  out aLeft * 0.6, aRight * 0.6
  clear gaReverbLeft, gaReverbRight
endin
"""


def key_of(degree):
    """MIDI key of a scale degree of D Dorian; degree 0 is D4."""
    octave, step = divmod(degree, len(DORIAN))
    return float(TONIC + 12 * octave + DORIAN[step])


def note(score, instrument, time, duration, key, velocity, depth, pan):
    # All eleven fields are given explicitly, in CsoundAC's order:
    # time, duration, status, instrument, key, velocity, phase, pan, depth,
    # height, pitches. Score.getCsoundScore() then writes them in the
    # p-field order documented in the orchestra above.
    score.append(time, duration, NOTE_ON, instrument, key, velocity,
                 0.0, pan, depth, 0.0, ALL_PITCH_CLASSES)


def bells(score, rng, start=0.5, end=12.5):
    """A random walk on the scale, with irregular rhythm and wandering pan."""
    time, degree, pan, count = start, 0, 0.3, 0
    while time < end:
        duration = rng.choice([2.5, 3.0, 3.5, 4.0])
        velocity = rng.randint(74, 94)
        depth = round(rng.uniform(0.1, 0.6), 2)
        note(score, BELL, time, duration, key_of(degree), velocity, depth, pan)
        count += 1
        time = round(time + rng.choice([0.5, 0.75, 1.0, 1.0, 1.5]), 3)
        degree = max(-3, min(9, degree + rng.choice([-2, -1, -1, 1, 1, 2])))
        pan = round(1.0 - pan + rng.uniform(-0.1, 0.1), 2)
    return count


def main():
    rng = random.Random(SEED)
    score = CsoundAC.Score()
    count = bells(score, rng)
    note(score, DRONE, 0.0, 15.0, 38.0, 84.0, 0.5, 0.5)   # D2
    note(score, DRONE, 7.0, 8.0, 45.0, 74.0, 0.5, 0.5)    # A2 joins halfway
    total = 18.0
    # 12 tones per octave: keys are written as whole MIDI key numbers.
    notes = score.getCsoundScore(12.0, False)
    csd = (
        "<CsoundSynthesizer>\n<CsOptions>\n-d\n</CsOptions>\n<CsInstruments>\n"
        + ORCHESTRA
        + "\n</CsInstruments>\n<CsScore>\n"
        + f"; Generated by code/nu-generate.py with seed {SEED}.\n"
        + f"i {REVERB} 0 {total:g}\n"
        + notes.strip("\n") + "\n"
        + f"e {total:g}\n"
        + "</CsScore>\n</CsoundSynthesizer>\n"
    )
    with open("nu.csd", "w", encoding="utf-8") as output:
        output.write(csd)
    print(f"nu.csd written: seed {SEED}, {count} bell notes, 2 drone notes, {total:g} seconds")


if __name__ == "__main__":
    main()
