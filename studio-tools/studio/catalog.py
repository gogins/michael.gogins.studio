"""Catalog of the published compositions, for the static viewer.

The catalog is generated by scanning docs/compositions/ only; it never
reads the archive, so it can list nothing that was not published. All paths
in it are relative to the catalog file itself.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional

from . import fsutil, naming
from .paths import Studio

SCHEMA = "ai-composition-studio/catalog/2"
CATALOG_NAME = "catalog.json"
#: Prompts larger than this are linked but not embedded in the catalog.
MAX_EMBEDDED_PROMPT_BYTES = 200_000


def _info_from_manifest(manifest: Dict[str, Any]) -> Dict[str, Any]:
    """The subset of a manifest the viewer shows; tolerant of missing keys."""
    def get(*keys: str) -> Any:
        value: Any = manifest
        for key in keys:
            if not isinstance(value, dict):
                return None
            value = value.get(key)
        return value

    analysis = get("render", "analysis") or {}
    browser = get("render", "browser") or {}
    info = {
        "ordinal": get("ordinal"),
        "created_at": get("created_at"),
        "ai_model": get("ai", "model"),
        "ai_agent": get("ai", "agent"),
        "generator": get("generator", "kind"),
        "seeds": get("generator", "seeds") or [],
        "csound": get("environment", "csound", "banner") or get("environment", "csound", "version"),
        "csoundac_revision": get("environment", "python", "csoundac_revision"),
        "python": get("environment", "python", "version"),
        "node": get("environment", "node", "version"),
        "duration_seconds": analysis.get("duration_seconds"),
        "sample_rate": analysis.get("sample_rate"),
        "channels": analysis.get("channels"),
        "peak_dbfs": analysis.get("peak_dbfs"),
        "rms_dbfs": analysis.get("rms_dbfs"),
        # Whether the version was performed in the viewer's engine when it was made.
        "browser_checked": browser.get("checked"),
        "browser_playable": browser.get("playable"),
        "browser_engine": " ".join(
            str(part) for part in ((browser.get("engine") or {}).get("package"),
                                   (browser.get("engine") or {}).get("version")) if part
        ),
        "browser_realtime_factor": browser.get("realtime_factor"),
        "new_prompts": get("new_prompts") or [],
        "warnings": get("validation", "warnings") or [],
        "notes": get("notes"),
    }
    return {key: value for key, value in info.items() if value not in (None, [], "")}


def _scan_state(
    name: str, directory: Path, prefix: str, texts: Dict[str, str], *, is_current: bool
) -> Optional[Dict[str, Any]]:
    files = fsutil.list_files(directory, skip_versions=is_current)
    state: Dict[str, Any] = {
        "path": prefix,
        "csd": None,
        "manifest": None,
        "prompts": [],
        "code": [],
        "derived": [],
        "logs": [],
        "info": {},
    }
    found = False
    for rel in files:
        kind = naming.classify(name, rel)
        if kind is None:
            continue  # not a studio file: never listed
        found = True
        full = directory / rel
        entry: Dict[str, Any] = {
            "file": rel.split("/")[-1],
            "path": prefix + rel,
            "bytes": full.stat().st_size,
        }
        if kind["kind"] == "csd":
            state["csd"] = entry
        elif kind["kind"] == "manifest":
            state["manifest"] = entry
            try:
                manifest = fsutil.read_json(full)
            except (OSError, ValueError):
                manifest = None
            if isinstance(manifest, dict):
                state["info"] = _info_from_manifest(manifest)
                if isinstance(manifest.get("title"), str):
                    state["title"] = manifest["title"]
        elif kind["kind"] == "prompts":
            entry["number"] = int(kind["number"])
            entry["sha256"] = fsutil.sha256_file(full)
            if entry["bytes"] <= MAX_EMBEDDED_PROMPT_BYTES:
                texts[entry["sha256"]] = full.read_text(encoding="utf-8", errors="replace")
            state["prompts"].append(entry)
        elif kind["kind"] == "code":
            entry["language"] = kind["language"]
            state["code"].append(entry)
        elif kind["kind"] == "derived":
            entry["kind"] = kind["derived"]
            state["derived"].append(entry)
        else:
            state["logs"].append(entry)
    if not found:
        return None
    state["prompts"].sort(key=lambda item: item["number"])
    new = set(state["info"].get("new_prompts", []))
    for prompt in state["prompts"]:
        prompt["new"] = prompt["file"] in new
    return state


def build(studio: Studio) -> Dict[str, Any]:
    compositions: List[Dict[str, Any]] = []
    if studio.published.is_dir():
        for directory in sorted(studio.published.iterdir(), key=lambda p: p.name.lower()):
            name = directory.name
            if not directory.is_dir() or directory.is_symlink() or not naming.COMPOSITION_RE.match(name):
                continue
            texts: Dict[str, str] = {}
            versions: List[Dict[str, Any]] = []
            current = _scan_state(name, directory, f"{name}/", texts, is_current=True)
            if current is not None:
                current.update({"id": "current", "is_current": True})
                current["ordinal"] = current["info"].get("ordinal")
                versions.append(current)
            for entry in sorted(directory.iterdir()):
                number = naming.parse_version_dir(entry.name)
                if number is None or not entry.is_dir() or entry.is_symlink():
                    continue
                state = _scan_state(name, entry, f"{name}/{entry.name}/", texts, is_current=False)
                if state is not None:
                    state.update({"id": entry.name, "is_current": False, "ordinal": number})
                    versions.append(state)
            if not versions:
                continue
            # Newest first: the current version, then archived versions descending.
            versions.sort(key=lambda v: (not v["is_current"], -(v["ordinal"] or 0)))
            title = next((v["title"] for v in versions if v.get("title")), name)
            for version in versions:
                version.pop("title", None)
            compositions.append(
                {
                    "name": name,
                    "title": title,
                    "path": f"{name}/",
                    "updated_at": next(
                        (v["info"]["created_at"] for v in versions if v["info"].get("created_at")), None
                    ),
                    "versions": versions,
                    "prompt_texts": texts,
                }
            )
    return {"schema": SCHEMA, "compositions": compositions}


def write(studio: Studio) -> Dict[str, Any]:
    """Regenerate catalog.json. The file is only rewritten when it changes."""
    catalog = build(studio)
    path = studio.published / CATALOG_NAME
    previous = None
    if path.is_file():
        try:
            previous = fsutil.read_json(path)
        except ValueError:
            previous = None
    unchanged = (
        isinstance(previous, dict)
        and {k: v for k, v in previous.items() if k != "generated_at"} == catalog
    )
    if unchanged:
        catalog["generated_at"] = previous.get("generated_at")
    else:
        catalog["generated_at"] = fsutil.utc_now()
        studio.published.mkdir(parents=True, exist_ok=True)
        fsutil.atomic_write_json(path, catalog)
    return {"path": path, "changed": not unchanged, "compositions": len(catalog["compositions"])}
